import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('artifacts/redesign', { recursive:true });
const browser = await chromium.launch({ channel:'msedge', headless:true, args:['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport:{ width:1440, height:1000 } });
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const checks=[];
try {
 await page.goto(process.env.BASE_URL || 'http://127.0.0.1:3100', { waitUntil:'networkidle' });
 await page.waitForFunction(()=>Number(document.querySelector('output')?.textContent?.replace('%',''))>0);
 await page.getByRole('button',{name:'暂停书写',exact:true}).click();
 await page.waitForTimeout(250);
 const stopped=await page.locator('output').textContent(); await page.waitForTimeout(450);
 assert.equal(await page.locator('output').textContent(),stopped); checks.push('pause freezes writing');
 await page.getByLabel('书写进度',{exact:true}).fill('1');
 await page.waitForTimeout(1400);
 assert.equal(await page.locator('output').textContent(),'100%');
 await page.screenshot({path:'artifacts/redesign/home-desktop.png',fullPage:true});
 await page.getByLabel('书写进度',{exact:true}).fill('0.5');
 await page.waitForTimeout(250); assert.equal(await page.locator('output').textContent(),'50%');
 await page.screenshot({path:'artifacts/redesign/arm-writing.png'});
 await page.getByRole('button',{name:'重新绘制',exact:true}).click();
 await page.waitForTimeout(200); assert(Number((await page.locator('output').textContent()).replace('%',''))<10); checks.push('seek backwards and replay');
 const navBefore=await page.locator('.nav-top').boundingBox();
 await page.locator('.app-content').evaluate(el=>el.scrollTop=el.scrollHeight);
 assert(await page.locator('.app-content').evaluate(el=>el.scrollTop>0));
 assert.deepEqual(await page.locator('.nav-top').boundingBox(),navBefore);
 assert.equal(await page.evaluate(()=>window.scrollY),0); checks.push('content scroll independent of navigation');
 await page.getByRole('button',{name:'收起菜单',exact:true}).click();
 assert.equal(await page.locator('.app-navigation').evaluate(el=>Math.round(el.getBoundingClientRect().width)),72);
 await page.getByRole('button',{name:'展开菜单',exact:true}).click(); checks.push('collapse and expand navigation');
 await page.getByRole('link',{name:'动作工作台',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.viewport-info')?.textContent?.includes('模型已就绪'));
 const canvasBefore=await page.locator('.viewport').boundingBox();
 await page.locator('.inspector').evaluate(el=>el.scrollTop=el.scrollHeight);
 assert(await page.locator('.inspector').evaluate(el=>el.scrollTop>0));
 assert.deepEqual(await page.locator('.viewport').boundingBox(),canvasBefore);
 await page.locator('.inspector').evaluate(el=>el.scrollTop=0); checks.push('inspector scroll independent of canvas');
 await page.getByLabel('动作名称',{exact:true}).fill('Navigation persistence');
 await page.getByRole('link',{name:'首页',exact:true}).click();
 await page.getByRole('link',{name:'动作工作台',exact:true}).click();
 assert.equal(await page.getByLabel('动作名称',{exact:true}).inputValue(),'Navigation persistence'); checks.push('unsaved project retained across route navigation');
 await page.keyboard.press('Control+s');
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('robot-motion-studio.project.v1')).name),'Navigation persistence'); checks.push('Ctrl+S saves current project');
 await page.waitForFunction(()=>document.querySelector('.viewport-info')?.textContent?.includes('模型已就绪'));
 await page.screenshot({path:'artifacts/redesign/studio-desktop.png'});
 await page.getByRole('button',{name:'学习指南',exact:true}).click();
 await page.getByRole('button',{name:'关闭学习指南',exact:true}).click();
 assert.equal(await page.getByRole('dialog').count(),0); checks.push('learning guide opens and closes');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'artifacts/redesign/studio-mobile.png'});
 assert(await page.locator('.app-content').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 await page.getByLabel('主导航').getByTitle('首页',{exact:true}).click();
 await page.getByLabel('书写进度',{exact:true}).fill('1'); await page.waitForTimeout(1400);
 await page.screenshot({path:'artifacts/redesign/home-mobile.png'});
 assert(await page.locator('.app-content').evaluate(el=>el.scrollWidth<=el.clientWidth+1)); checks.push('mobile routes have no horizontal overflow');
 assert.deepEqual(errors,[]); checks.push('no browser runtime errors');
 await writeFile('artifacts/redesign/checks.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));
} catch(e) { await page.screenshot({path:'artifacts/redesign/failure.png'}); console.error(e); process.exitCode=1; }
finally { await Promise.race([browser.close(),new Promise(r=>setTimeout(r,4000))]); process.exit(process.exitCode||0); }
